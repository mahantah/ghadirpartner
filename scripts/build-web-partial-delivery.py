"""Build the typed web delivery asset from the same validated policy as its server endpoint."""

from __future__ import annotations

import argparse
import json
import subprocess
import tempfile
from pathlib import Path


class WebPartialDeliveryBuilder:
    """Keep build-time policy validation separate from compiler and filesystem effects."""

    def __init__(self, root: Path) -> None:
        """Inject the repository containing the finite web feature package."""
        self.root = root

    def _policy(self) -> dict[str, object]:
        raw: object = json.loads(
            (self.root / "config/partial-dispatch.yaml").read_text()
        )
        keys = {
            "maximum_quantity",
            "maximum_reason_bytes",
            "carriers",
            "tracking_carriers",
            "ready_statuses",
        }
        if not isinstance(raw, dict) or set(raw) != keys:
            raise ValueError("Invalid partial delivery policy keys")
        result: dict[str, object] = {key: raw[key] for key in keys}
        for key in ("maximum_quantity", "maximum_reason_bytes"):
            value = result[key]
            if type(value) is not int or not 1 <= value <= 10000:
                raise ValueError("Invalid partial delivery limit")
        lists: dict[str, list[str]] = {}
        for key in ("carriers", "tracking_carriers", "ready_statuses"):
            values = result[key]
            if (
                not isinstance(values, list)
                or not values
                or not all(isinstance(v, str) and v.strip() for v in values)
            ):
                raise ValueError("Invalid partial delivery choices")
            lists[key] = [str(v) for v in values]
        if not set(lists["tracking_carriers"]).issubset(lists["carriers"]):
            raise ValueError("Unknown tracking carrier")
        return result

    def build(self, check: bool) -> None:
        """Compile strictly, embed validated public policy, and optionally compare the committed asset."""
        policy = self._policy()
        compiler = self.root / "tooling/partial-delivery-web/node_modules/.bin/tsc"
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory) / "web.js"
            subprocess.run(
                [
                    str(compiler),
                    "-p",
                    str(self.root / "config/partial-delivery-web.tsconfig.json"),
                    "--noEmit",
                    "false",
                    "--outFile",
                    str(output),
                ],
                check=True,
            )
            prefix = (
                "/* Generated by scripts/build-web-partial-delivery.py; edit the typed source. */\nconst GP_WEB_PARTIAL_POLICY = "
                + json.dumps(policy, ensure_ascii=False, sort_keys=True)
                + ";\n"
            )
            compiled = prefix + output.read_text()
        target = self.root / "assets/partial-delivery-web.js"
        if check:
            if target.read_text() != compiled:
                raise ValueError("Generated partial delivery asset is stale")
        else:
            target.write_text(compiled)


def main() -> None:
    """Expose a deterministic build/check command with no network or runtime data access."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    WebPartialDeliveryBuilder(Path(__file__).resolve().parents[1]).build(
        arguments.check
    )


if __name__ == "__main__":
    main()
