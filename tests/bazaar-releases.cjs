/* Verify role visibility, lazy metadata loading and secret handling with synthetic DOM fixtures. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require(process.env.GP_JSDOM_PATH || 'jsdom');
const source = fs.readFileSync('assets/bazaar-releases.js', 'utf8');
const tick = () => new Promise(resolve => setTimeout(resolve, 0));
(async () => {
  const dom = new JSDOM('<div id="app"><nav class="topnav"><div id="gpSystem"><div class="nav-submenu"></div></div></nav><main id="workspace"><section class="tab" id="home">Home</section></main></div>', { runScripts: 'outside-only', url: 'https://example.test/app.html' });
  const { window } = dom;
  let admin = false;
  let rejectToken = true;
  const calls = [];
  window.has = role => role === 'admin' && admin;
  window.setSidebar = () => {};
  window.fetch = async (path, options) => {
    calls.push({ path, options });
    if (!options.method) return { ok: true, text: async () => JSON.stringify({ csrf: 'fixture-csrf', releases: [{id:'a'.repeat(32),state:'ready',version_name:'1.0',version_code:1,bytes:100,created_at:'2026-11-18T00:00:00Z',file_removed:false,sha256:'f'.repeat(64)}], token_configured:false,environment_token:false,ready:true,network_ready:true,policy:{maximum_apk_bytes:16777216,chunk_bytes:524288,maximum_changelog_chars:4000,package_name:'ir.ghadirpartner.portalapp'} }) };
    if (rejectToken) return { ok: false, text: async () => "توکن پیشخان معتبر نیست." };
    return { ok: true, text: async () => JSON.stringify({ configured: true }) };
  };
  window.eval(source);
  const link = window.document.querySelector('[data-gp-app-releases]');
  assert(link.classList.contains('hidden'));
  assert(!link.hasAttribute('data-tab'), 'Do not register an unknown tab in legacy navigation permissions');
  assert.equal(calls.length, 0, 'No request before an admin opens the page');
  admin = true; window.document.getElementById('app').setAttribute('data-test-session', 'admin'); await tick();
  assert(!link.classList.contains('hidden'));
  link.click(); await tick(); await tick();
  assert.equal(calls.length, 1);
  assert.equal(calls[0].path, '/api/admin/app-releases');
  const page = window.document.getElementById('gpAppReleasesPage');
  assert(!page.classList.contains('hidden'));
  assert.equal(page.parentElement.id, 'workspace', 'Mount inside the existing workspace rather than below the sidebar');
  assert(link.querySelector('.gp-menu-text'), 'Respect collapsed sidebar label styling');
  assert(!window.document.querySelector('details'), 'Release forms are open by default');
  const publish = [...page.querySelectorAll('button')].find(b => b.textContent === 'بررسی و انتشار خودکار');
  assert(publish.disabled, 'Cannot publish before configuring a token');
  const token = page.querySelector('[name=token]'); token.value = 'fixture-token-never-render';
  token.closest('form').dispatchEvent(new window.Event('submit', {cancelable:true})); await tick(); await tick();
  assert(page.querySelector('[role=status]').textContent.includes('توکن پیشخان معتبر نیست.'), 'Show existing plaintext API error messages safely');
  rejectToken = false;
  token.closest('form').dispatchEvent(new window.Event('submit', {cancelable:true})); await tick(); await tick();
  const write = calls.find(call => call.options.method === 'POST');
  assert.equal(write.options.headers['X-GP-Release-CSRF'], 'fixture-csrf');
  assert.equal(JSON.parse(write.options.body).action, 'save_token');
  assert.equal(token.value, '', 'Forget the typed token after saving');
  assert(!page.textContent.includes('fixture-token-never-render'));
  admin = false; window.document.getElementById('app').setAttribute('data-test-session', 'customer'); await tick();
  assert(link.classList.contains('hidden'));
  assert(page.classList.contains('hidden'));
  assert(!page.textContent.includes('1.0'), 'Clear administrator release metadata on logout');
  dom.window.close();
  console.log('PASS: admin sidebar visibility, open forms, lazy loading, CSRF, disabled publication and logout redaction');
})().catch(error => { console.error(error); process.exitCode = 1; });
